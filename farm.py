def _validate_polygon(polygon) -> None:
    if not polygon or len(polygon) < 4:
        raise HTTPException(
            status_code=400,
            detail="Polygon needs at least 3 points and must be closed.",
        )


class LegacyAnalyzeRequest(BaseModel):
    """
    Request model for the OLD sequential /analyze route.

    Deliberately polygon-only, and deliberately NOT the same model as the
    agent route.

    The legacy route does not run the agent pipeline, so it has no way to
    use crop context. If it shared AnalyzeRequest it would accept
    crop_type and planting_date, return 200, and silently discard them —
    the caller would get a report with no crop context and no indication
    why. A 422 saying the field is not supported here is honest; a silent
    discard is not.

    See the deprecation note on analyze_farm() below.
    """

    polygon: list[list[float]]

    model_config = {"extra": "forbid"}


class AnalyzeRequest(BaseModel):
    """
    Request model for the agent route.

    polygon is the only required field.

    The four crop fields are OPTIONAL and must stay that way. Every farm
    already saved in the database has none of them, and the product flow
    is draw-a-boundary-then-analyse. Crop context changes how a reading
    is INTERPRETED; it is never a gate on producing one.

        polygon only              -> Farm Watch behaves exactly as before
        polygon + crop context    -> crop-aware interpretation

    Empty strings are coerced to None. A browser form submits "" for an
    untouched select, and "" must behave identically to a field that was
    never sent — otherwise the legacy path depends on which client is
    calling.

    Values are passed through UNNORMALISED. crop_context.py is the single
    place that maps "Maize" and "corn" onto one key; duplicating that
    mapping here is how two layers quietly stop agreeing.
    """

    polygon: list[list[float]]

    crop_type: Optional[str] = None
    planting_date: Optional[str] = None
    irrigation_type: Optional[str] = None

    # Normally generated by Tagintell. A saved farm may send its existing
    # value back so repeated analyses stay attached to the same season.
    season_id: Optional[str] = None

    @field_validator(
        "crop_type",
        "irrigation_type",
        "season_id",
        mode="before",
    )
    @classmethod
    def blank_to_none(cls, value):
        if value is None:
            return None
        text = str(value).strip()
        return text or None

    @field_validator("planting_date", mode="before")
    @classmethod
    def valid_optional_planting_date(cls, value):
        """
        Planting date is optional.

        If supplied, it must be a real calendar date written exactly as:

            YYYY-MM-DD

        Empty strings are treated as missing values.

        Two checks, and both are needed.

        The regex gate is NOT redundant with fromisoformat. On Python
        3.11+ that function also accepts compact dates (20260501) and ISO
        week dates (2026-W18-5). Without the gate this API would accept
        formats its own error message says it does not, and
        crop_context.py would parse them into a real
        days_after_planting — two layers quietly agreeing on a format
        nobody intended.

        fromisoformat is still needed after the gate, because a regex
        cannot reject an impossible calendar date such as 2026-02-30.

        crop_context._parse_date is deliberately not used here: it is a
        private helper of another service, and it is intentionally more
        permissive than this boundary should be.
        """
        if value is None:
            return None

        text = str(value).strip()

        if not text:
            return None

        # Enforce the exact API format before parsing the calendar date.
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", text):
            raise ValueError(
                "planting_date must be a calendar date in YYYY-MM-DD "
                "format."
            )

        try:
            date.fromisoformat(text)
        except ValueError as exc:
            raise ValueError(
                "planting_date must be a valid calendar date in "
                "YYYY-MM-DD format."
            ) from exc

        return text


def _analysis_kwargs(request: AnalyzeRequest) -> dict:
    """The optional crop fields, in one place for the agent route."""
    return {
        "crop_type": request.crop_type,
        "planting_date": request.planting_date,
        "irrigation_type": request.irrigation_type,
        "season_id": request.season_id,
    }


def _extract_attention_description(attention_area) -> str:
    """
    Safely extracts the plain-English description from attention_area.

    KNOWN DEFECT, retained only because this legacy route is frozen
    pending retirement: the "general area of the farm" fallback
    MANUFACTURES a location the pipeline never identified. attention_area
    is None precisely when no area was found, and the agent pipeline
    treats that None as meaningful. Do not copy this helper anywhere.
    """
    if isinstance(attention_area, dict):
        return attention_area.get(
            "description", "general area of the farm"
        )
    if isinstance(attention_area, str) and attention_area:
        return attention_area
    return "general area of the farm"


@router.post("/analyze")
async def analyze_farm(request: LegacyAnalyzeRequest):
    """
    Original sequential route (no LangGraph).

    DEPRECATED — DO NOT ADD FEATURES HERE.
    --------------------------------------
    This route calls gee.py and classify_stress directly, skipping the
    detection, interpretation and report agents. It therefore has none of
    the protections the rest of the system depends on:

      - no assessment_scope, so a partly-observed field is described as
        if it had been fully assessed
      - "general area of the farm" fabricates a location the pipeline
        never identified and tells the farmer to go and scout it
      - it reads image_info["cloud_cover_percent"], which gee.py no
        longer returns, so the response reports "Unknown"
      - stress_map_url now points at a RELATIVE variation map whose
        colours are rescaled per observation, presented here under a name
        implying an absolute health map

    Left scientifically unchanged so Step 3 does not alter a response
    contract mid-migration. It does NOT receive crop context.

    RETIREMENT CHECK — run before Step 3 is finished:

        Get-ChildItem -Path frontend -Recurse -Include *.tsx,*.ts |
            Select-String -Pattern "/analyze"

    If the frontend only calls /analyze/agent, delete this route and
    _extract_attention_description with it. If anything calls /analyze,
    migrate that caller deliberately and check the response shape at the
    same time.
    """
    _validate_polygon(request.polygon)

    try:
        # Step 1: GEE fetches selected-image analysis + recent comparison
        gee_result = calculate_all_indices_for_polygon(request.polygon)

        ndvi = gee_result.get("ndvi")
        ndwi = gee_result.get("ndwi")
        ndre = gee_result.get("ndre")
        savi = gee_result.get("savi")
        gndvi = gee_result.get("gndvi")

        stress_map_url = gee_result.get("stress_map_url")
        image_info = gee_result.get("image_info", {})
        attention_source = gee_result.get("attention_source", "unknown")
        recent_comparison = gee_result.get("recent_comparison", {})

        attention_area_raw = gee_result.get("attention_area", "")
        attention_area_desc = _extract_attention_description(
            attention_area_raw
        )

        farm_area = gee_result.get("farm_area", {})
        area_ha = farm_area.get("hectares", gee_result.get("area_ha"))
        area_acres = farm_area.get("acres", gee_result.get("area_acres"))

        # Step 2: Classify stress using the updated rule-based signature.
        # No crop_context is passed: this route cannot supply one, and
        # its absence keeps the classifier on its legacy path.
        classification = classify_stress(ndvi, ndwi, ndre, savi, gndvi)

        stress_type = classification["stress_type"]
        stress_title = classification["title"]
        severity = classification["severity"]
        recommendation = classification["recommendation"]
        confidence = classification.get("confidence", "medium")

        severity_str = (
            severity.value
            if hasattr(severity, "value")
            else str(severity)
        )
        stress_type_str = (
            stress_type.value
            if hasattr(stress_type, "value")
            else str(stress_type)
        )

        color_map = {
            "none": "#22c55e",
            "mild": "#facc15",
            "moderate": "#f97316",
            "severe": "#ef4444",
        }
        color = color_map.get(severity_str, "#22c55e")

        urgency_map = {
            "none": "low",
            "mild": "low",
            "moderate": "medium",
            "severe": "high",
        }
        urgency = urgency_map.get(severity_str, "medium")

        # Step 3: Build farmer-friendly text
        if severity_str == "none":
            summary = (
                "No major crop stress was detected from the selected "
                "satellite image."
            )
            explanation = (
                "Vegetation condition looks generally stable across the "
                "farm based on the satellite image used for this "
                "analysis."
            )
            action = (
                "Continue routine field checks and keep monitoring "
                "changes through the season."
            )
        else:
            summary = (
                f"{stress_title}. The main area needing attention "
                f"appears in {attention_area_desc}."
            )
            explanation = (
                f"The satellite signal suggests "
                f"{stress_type_str.replace('_', ' ')} in parts of the "
                f"farm. The strongest concern appears in "
                f"{attention_area_desc}."
            )
            action = recommendation

        # Step 4: Return aligned response
        return {
            "title": stress_title,
            "summary": summary,
            "explanation": explanation,
            "action": action,
            "urgency": urgency,
            "stress_map_url": stress_map_url,
            "severity": severity_str,
            "color": color,
            "recommendation": recommendation,
            "attention_area": attention_area_desc,
            "hotspot_summary": (
                f"Main concern detected in {attention_area_desc}."
            ),
            "image_info": {
                "source": image_info.get("source", "Sentinel-2"),
                "date": image_info.get("date", "Unknown"),
                "cloud_cover_percent": image_info.get(
                    "cloud_cover_percent", "Unknown"
                ),
                "search_window_start": image_info.get(
                    "search_window_start", "Unknown"
                ),
                "search_window_end": image_info.get(
                    "search_window_end", "Unknown"
                ),
                "selection_mode": image_info.get("selection_mode"),
                "candidate_count": image_info.get("candidate_count"),
                "clean_candidate_count": image_info.get(
                    "clean_candidate_count"
                ),
            },
            "farm_area": {
                "hectares": area_ha,
                "acres": area_acres,
            },
            "technical_details": {
                "ndvi": round(ndvi, 4) if ndvi is not None else None,
                "ndwi": round(ndwi, 4) if ndwi is not None else None,
                "ndre": round(ndre, 4) if ndre is not None else None,
                "savi": round(savi, 4) if savi is not None else None,
                "gndvi": round(gndvi, 4) if gndvi is not None else None,
                "stress_type": stress_type_str,
                "confidence": confidence,
                "attention_source": attention_source,
                "selection_mode": image_info.get("selection_mode"),
                "candidate_count": image_info.get("candidate_count"),
                "clean_candidate_count": image_info.get(
                    "clean_candidate_count"
                ),
                "recent_ndvi_composite": recent_comparison.get(
                    "recent_ndvi_composite"
                ),
                "recent_ndre_composite": recent_comparison.get(
                    "recent_ndre_composite"
                ),
                "recent_ndwi_composite": recent_comparison.get(
                    "recent_ndwi_composite"
                ),
                "recent_savi_composite": recent_comparison.get(
                    "recent_savi_composite"
                ),
                "recent_gndvi_composite": recent_comparison.get(
                    "recent_gndvi_composite"
                ),
                "ndvi_delta_recent": recent_comparison.get(
                    "ndvi_delta_recent"
                ),
                "ndre_delta_recent": recent_comparison.get(
                    "ndre_delta_recent"
                ),
                "ndwi_delta_recent": recent_comparison.get(
                    "ndwi_delta_recent"
                ),
                "savi_delta_recent": recent_comparison.get(
                    "savi_delta_recent"
                ),
                "gndvi_delta_recent": recent_comparison.get(
                    "gndvi_delta_recent"
                ),
                "recent_condition_status": recent_comparison.get(
                    "recent_condition_status"
                ),
                "data_source": "Sentinel-2 via Google Earth Engine",
            },
            "recent_comparison": recent_comparison,
        }

    except HTTPException:
        raise

    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Analysis failed: {str(e)}",
        )


@router.post("/analyze/agent")
async def analyze_farm_with_agents(request: AnalyzeRequest):
    """
    LangGraph agent route — the canonical path, and the only one that
    receives crop context.
    """
    _validate_polygon(request.polygon)

    try:
        return run_farm_watch_analysis(
            polygon=request.polygon,
            **_analysis_kwargs(request),
        )

    except HTTPException:
        raise

    except Exception as e:
        raise HTTPException(
            status_code=500,
            detail=f"Agent analysis failed: {str(e)}",
        )